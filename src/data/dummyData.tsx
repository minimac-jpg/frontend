// TYPES
export type Release = {
  id: number;
  name: string;
  numberOfArtifacts: number;
  status: string;
  team: string;
  scrumMaster: string;
  estProdDate: string;
  stageDate: string;
  archivedDate: string;
  defaultEnv: string;
  releaseChecklist: ReleaseChecklist[];
};

export type Artifact = {
  id: number;
  name: string;
  appKey: string;
  releaseName: string;
  version: string;
  buildNumber: number;
  hash: string;
  buildTime: string;
  createdAt: string;
  updatedAt: string;
  deployedAt: string;
  archivedDate?: string | null;
  status: string;
  ticketNumber: string;
  isRemoved: boolean;
  isDeployed: boolean;
};

export type ArtifactDeploy = {
  id: number;
  name: string;
  appKey: string;
  releaseName: string;
  version: string;
  buildNumber: number;
  hash: string;
  buildTime: string;
  updatedBy: string;
  updatedAt: string;
  deployedAt: string;
  status: string;
};

export type ArtifactReleaseHistory = {
  id: string;
  name: string;
  host: string;
  version: string;
  hash: string;
  buildTime: string;
  status: string;
  dateArchived?: string | null;
};

export type Environment = {
  id: string;
  name: string;
  type: string;
  silos: string;
  deploymentType: string[];
  deploymentHandler: string;
  updatedAt: string;
  updatedBy: string;
};

export type DatabaseScript = {
  id: string;
  name: string;
  releaseName: string;
  database: string;
  type: string;
  hash: string;
  pullRequest: string;
  createdAt: string;
  updatedAt: string;
  deployedAt: string;
  fileNames: string[];
  isRemoved: boolean;
};

export type ReleaseChecklist = {
  releaseName: string;
  itemName: string;
  itemValue: "yes" | "no" | null;
  signOffBy: string | null;
  signOffAt: string | null;
  updatedBy: string | null;
  updatedAt: string | null;
  isRequired: boolean;
};

export type Deployments = {
  id: number;
  deploymentNumber: string;
  environment: string;
  numberOfArtifacts: number;
  status: string;
  bat: string;
  createdBy: string;
  createdAt: string;
  ticketNumber: string;
  rollback: boolean;
  artifacts: ArtifactDeploy[] | null;
  releaseName: string;
};

